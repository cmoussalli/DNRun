<#
.SYNOPSIS
    Installs DNRun.exe to a directory on PATH.

.DESCRIPTION
    Copies ./artifacts/DNRun.exe to the install directory (C:\CMouss\DNRun by default), writes the
    dnuget.cmd shim next to it, and adds that directory to the user PATH if it is not already
    there. DNRun is installed once and used from every repository - it is never copied into a
    project.

    Open a new terminal afterwards so the updated PATH is picked up.

.EXAMPLE
    ./build/install.ps1
    ./build/install.ps1 -InstallDir 'D:\Tools\DNRun'
#>
[CmdletBinding()]
param(
    [string]$InstallDir = 'C:\CMouss\DNRun',
    [switch]$SkipPath
)

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
$source = Join-Path $repoRoot 'artifacts/DNRun.exe'

if (-not (Test-Path $source)) {
    throw "$source not found. Run ./build/publish.ps1 first."
}

if (-not (Test-Path $InstallDir)) {
    New-Item -ItemType Directory -Path $InstallDir -Force | Out-Null
}

$target = Join-Path $InstallDir 'DNRun.exe'

# A running DNRun.exe holds a lock on the file; say so plainly instead of failing cryptically.
try {
    Copy-Item $source $target -Force
}
catch [System.IO.IOException] {
    throw "Could not write $target - is DNRun.exe currently running? ($($_.Exception.Message))"
}

Write-Host "Installed $target" -ForegroundColor Green

# 'dnuget 1.2.14' is DNRun.exe with the nuget verb; a shim beside the executable is cheaper than a
# second copy of a Native AOT binary, and follows the same PATH entry it does.
$shim = Join-Path $InstallDir 'dnuget.cmd'
Set-Content -Path $shim -Encoding ascii -Value @(
    '@echo off',
    'rem Generated by build/install.ps1. dnuget is DNRun.exe with the nuget verb.',
    '"%~dp0DNRun.exe" nuget %*',
    'exit /b %ERRORLEVEL%'
)

Write-Host "Installed $shim" -ForegroundColor Green

if ($SkipPath) { return }

$userPath = [Environment]::GetEnvironmentVariable('PATH', 'User')
$entries = @($userPath -split ';' | Where-Object { $_ })

if ($entries -contains $InstallDir) {
    Write-Host "PATH already contains $InstallDir"
}
else {
    $updated = (@($entries) + $InstallDir) -join ';'
    [Environment]::SetEnvironmentVariable('PATH', $updated, 'User')
    Write-Host "Added $InstallDir to the user PATH." -ForegroundColor Green
    Write-Host 'Open a new terminal for the change to take effect.'
}

Write-Host ''
Write-Host 'Verify with:'
Write-Host '    cd <any .NET repository>'
Write-Host '    dnrun list        # the projects you can run'
Write-Host '    dnuget list       # the packages you can version'
